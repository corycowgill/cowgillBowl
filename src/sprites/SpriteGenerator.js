// ── Color helper ──
function hexToRgb(hex) {
  return {
    r: (hex >> 16) & 0xff,
    g: (hex >> 8) & 0xff,
    b: hex & 0xff,
  };
}

function darken(color, amount) {
  return {
    r: Math.max(0, color.r - amount),
    g: Math.max(0, color.g - amount),
    b: Math.max(0, color.b - amount),
  };
}

function lighten(color, amount) {
  return {
    r: Math.min(255, color.r + amount),
    g: Math.min(255, color.g + amount),
    b: Math.min(255, color.b + amount),
  };
}

// ── Sprite Generator ──
export default class SpriteGenerator {
  // Generate all team spritesheets and register animations
  static generate(scene, teams) {
    for (const team of teams) {
      SpriteGenerator.generateTeamSheet(scene, team);
    }
    SpriteGenerator.registerAnimations(scene, teams);
  }

  static generateTeamSheet(scene, team) {
    const primary = hexToRgb(team.colors.primary);
    const secondary = hexToRgb(team.colors.secondary);
    const accent = hexToRgb(team.colors.accent);
    const skin = { r: 210, g: 170, b: 130 };
    const pants = darken(primary, 40);
    const shoe = { r: 30, g: 30, b: 30 };
    const shadow = { r: 0, g: 0, b: 0 };
    const white = { r: 255, g: 255, b: 255 };

    const palette = {
      '0': null,          // transparent
      '1': secondary,     // helmet
      '2': primary,       // jersey
      '3': skin,          // skin
      '4': pants,         // pants
      '5': white,         // stripe/number
      '6': shoe,          // shoes
      '7': accent,        // helmet stripe/facemask
      '8': shadow,        // ground shadow
    };

    // Count total frames
    const animKeys = Object.keys(ANIMATIONS);
    let totalFrames = 0;
    for (const key of animKeys) totalFrames += ANIMATIONS[key].length;

    // Create canvas
    const sheetW = totalFrames * FRAME_W;
    const sheetH = FRAME_H;
    const canvas = document.createElement('canvas');
    canvas.width = sheetW;
    canvas.height = sheetH;
    const ctx = canvas.getContext('2d');

    // Draw each frame
    let frameIdx = 0;
    for (const key of animKeys) {
      for (const frameData of ANIMATIONS[key]) {
        const ox = frameIdx * FRAME_W;
        for (let y = 0; y < FRAME_H; y++) {
          const row = frameData[y];
          for (let x = 0; x < FRAME_W; x++) {
            const ch = row[x] || '0';
            const color = palette[ch];
            if (!color) continue;
            if (ch === '8') {
              ctx.fillStyle = `rgba(0,0,0,0.25)`;
            } else {
              ctx.fillStyle = `rgb(${color.r},${color.g},${color.b})`;
            }
            ctx.fillRect(ox + x, y, 1, 1);
          }
        }
        frameIdx++;
      }
    }

    // Register as Phaser texture
    const key = `player_${team.abbr}`;
    if (scene.textures.exists(key)) scene.textures.remove(key);
    const tex = scene.textures.addCanvas(key, canvas);

    // Add frames
    frameIdx = 0;
    for (const animKey of animKeys) {
      for (let f = 0; f < ANIMATIONS[animKey].length; f++) {
        tex.add(frameIdx, 0, frameIdx * FRAME_W, 0, FRAME_W, FRAME_H);
        frameIdx++;
      }
    }
  }

  static registerAnimations(scene, teams) {
    const animKeys = Object.keys(ANIMATIONS);

    for (const team of teams) {
      const key = `player_${team.abbr}`;
      let frameOffset = 0;

      for (const animKey of animKeys) {
        const count = ANIMATIONS[animKey].length;
        const frames = [];
        for (let i = 0; i < count; i++) {
          frames.push({ key, frame: frameOffset + i });
        }

        const animName = `${team.abbr}_${animKey}`;
        if (scene.anims.exists(animName)) continue;

        const rates = {
          idle: 3,
          run: 10,
          catch: 6,
          tackle: 8,
          down: 1,
          celebrate: 5,
        };

        scene.anims.create({
          key: animName,
          frames,
          frameRate: rates[animKey] || 8,
          repeat: (animKey === 'idle' || animKey === 'run' || animKey === 'celebrate') ? -1 : 0,
        });

        frameOffset += count;
      }
    }
  }

  // Get animation key for a team
  static animKey(teamAbbr, anim) {
    return `${teamAbbr}_${anim}`;
  }

  static get FRAME_W() { return FRAME_W; }
  static get FRAME_H() { return FRAME_H; }
}
